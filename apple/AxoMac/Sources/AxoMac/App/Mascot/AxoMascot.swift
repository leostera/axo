import AppKit
import AxoMascot
import Observation
import SwiftUI

/// Plays one artboard of the mascot and returns each frame as an image.
@MainActor
public protocol MascotFrameSource: AnyObject {
  /// Advances the animation by `seconds` and draws it. Returns nil when nothing changed.
  func nextFrame(advancingBy seconds: TimeInterval) async throws -> CGImage?
}

/// Where mascot frames come from. The shipped app installs the Rive-backed one
/// (`AxoMascotRive`), which keeps the Rive framework out of this library and its tests.
@MainActor
public protocol MascotAnimation {
  func makeFrameSource(artboard: String, pixelSize: CGSize) async throws -> any MascotFrameSource
  /// A live Axo for a window, or nil if the animation cannot load.
  func makePuppet(artboard: String) -> (any MascotPuppet)?
}

/// A live Axo in a window: it looks around and blinks on its own, and this tells it where to
/// look, how to react and whether it is waiting on something.
@MainActor
public protocol MascotPuppet: AnyObject {
  var view: AnyView { get }
  /// From -100 (left, up) to 100 (right, down).
  func look(x: Double, y: Double)
  func stopLooking()
  func react(_ reaction: MascotReaction)
  /// Gills flutter and Axo bobs; on the `Loader` artboard it also spins.
  func setLoading(_ loading: Bool)
}

/// The animated Axo axolotl in the menu bar and the Dock.
///
/// The animation (`assets/mascot/axo.riv`, generated by `packages/axo-mascot`) decides when to
/// blink; this only plays it where the system takes images. The `Mark` artboard becomes a template
/// image, so the menu bar tints it; the `Icon` artboard replaces the Dock icon. With Reduce Motion
/// on, the mascot holds still and the Dock shows the bundle's icon.
@MainActor
@Observable
final class AxoMascot {
  /// Names in `packages/axo-mascot/src/mascot.ts` (`MascotContract`).
  enum Contract {
    static let markArtboard = "Mark"
    static let iconArtboard = "Icon"
    static let faceArtboard = "Face"
    static let loaderArtboard = "Loader"
  }

  /// Installed by the app's entry point before the app starts; nil leaves the static symbol.
  static var installedAnimation: (any MascotAnimation)?

  /// In points; the `Mark` artboard is 1064 x 604.
  static let menuBarSize = CGSize(width: 28, height: 16)
  static let dockIconPixels = CGSize(width: 512, height: 512)
  static let framesPerSecond = 30.0

  private(set) var menuBarImage: NSImage?

  @ObservationIgnored private var task: Task<Void, Never>?
  @ObservationIgnored private var restingMenuBarImage: NSImage?

  func start(animatesDockIcon: Bool) {
    guard task == nil, let animation = Self.installedAnimation else { return }
    task = Task { [weak self] in
      await self?.run(animation, animatesDockIcon: animatesDockIcon)
    }
  }

  private func run(_ animation: any MascotAnimation, animatesDockIcon: Bool) async {
    let scale = NSScreen.main?.backingScaleFactor ?? 2
    let mark: any MascotFrameSource
    let icon: (any MascotFrameSource)?
    do {
      mark = try await animation.makeFrameSource(
        artboard: Contract.markArtboard,
        pixelSize: CGSize(width: Self.menuBarSize.width * scale, height: Self.menuBarSize.height * scale))
      icon =
        animatesDockIcon
        ? try await animation.makeFrameSource(artboard: Contract.iconArtboard, pixelSize: Self.dockIconPixels)
        : nil
    } catch {
      NSLog("Axo mascot unavailable: \(error)")
      return
    }

    let frameInterval = Duration.seconds(1 / Self.framesPerSecond)
    let clock = ContinuousClock()
    var last = clock.now
    var isFirstFrame = true
    while !Task.isCancelled {
      if NSWorkspace.shared.accessibilityDisplayShouldReduceMotion && !isFirstFrame {
        holdStill()
        await Self.accessibilityDisplayOptionsChange()
        last = clock.now
        continue
      }
      let now = clock.now
      let elapsed = isFirstFrame ? 0 : (now - last).timeInterval
      last = now
      do {
        if let frame = try await mark.nextFrame(advancingBy: elapsed) {
          let image = NSImage(cgImage: frame, size: Self.menuBarSize)
          image.isTemplate = true
          image.accessibilityDescription = "Axo"
          menuBarImage = image
          if isFirstFrame { restingMenuBarImage = image }
        }
        if let icon, let frame = try await icon.nextFrame(advancingBy: elapsed) {
          NSApp.applicationIconImage = NSImage(cgImage: frame, size: Self.dockIconPixels)
        }
      } catch {
        NSLog("Axo mascot stopped: \(error)")
        holdStill()
        return
      }
      isFirstFrame = false
      try? await clock.sleep(until: now + frameInterval)
    }
  }

  /// The open-eyed first frame in the menu bar and the bundle's icon in the Dock.
  private func holdStill() {
    if let restingMenuBarImage { menuBarImage = restingMenuBarImage }
    NSApp.applicationIconImage = nil
  }

  private static func accessibilityDisplayOptionsChange() async {
    let changes = NSWorkspace.shared.notificationCenter.notifications(
      named: NSWorkspace.accessibilityDisplayOptionsDidChangeNotification)
    for await _ in changes { return }
  }
}

extension Duration {
  fileprivate var timeInterval: TimeInterval {
    let (seconds, attoseconds) = components
    return TimeInterval(seconds) + TimeInterval(attoseconds) / 1e18
  }
}
